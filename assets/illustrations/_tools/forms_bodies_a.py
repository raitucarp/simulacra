DARK = ' fill="#000" fill-opacity=".16"'


def shade(el):
    """A darkening overlay copy of a shape (no stroke)."""
    return el.replace('/>', DARK + '/>')


def rot(el, a, cx=128, cy=128):
    return el.replace('/>', f' transform="rotate({n(a)} {n(cx)} {n(cy)})"/>')


def thick(d, f, w=12):
    """A stroked limb with an outline: fg stroke under a narrower fill-color stroke."""
    return L(d, 'f', w + 6) + L(d, f, w)


