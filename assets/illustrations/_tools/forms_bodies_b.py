def pine_d(cx, top, h, w):
    """Three-tier pine silhouette as one closed path."""
    pts = [(cx, top), (cx + w * .42, top + h * .3), (cx + w * .26, top + h * .3), (cx + w * .72, top + h * .6),
           (cx + w * .5, top + h * .6), (cx + w, top + h)]
    return poly(pts + [(2 * cx - x, y) for x, y in reversed(pts[1:])])


