//! Writing `table.rs`: a header, then one line per subgroup so the table stays short.

use super::{EmojiData, EmojiRecord};
use crate::domain::emoji::EmojiGroup;

/// The Rust source of the emoji table for `data`.
pub fn render_table(data: &EmojiData) -> String {
    let mut out = String::new();
    out.push_str("//! Emoji names, groups and skin tones from Unicode's emoji-test.txt (generated by the\n");
    out.push_str("//! `emoji-table` tool from `src/domain/emoji/generate`; do not edit by hand).\n");
    out.push_str("//!\n//! Data © Unicode, Inc., under the Unicode License v3 (see THIRD_PARTY.md).\n\n");
    out.push_str("use super::{e, Emoji, EmojiGroup::*};\n\n");
    out.push_str(&format!("/// The Unicode emoji version the table was generated from.\npub const UNICODE_EMOJI_VERSION: &str = {:?};\n\n", data.version));
    out.push_str("/// Every fully-qualified emoji, in CLDR order.\n#[rustfmt::skip]\npub static EMOJI: &[Emoji] = &[\n");
    for line in subgroup_lines(&data.emoji) {
        out.push_str(&line);
        out.push('\n');
    }
    out.push_str("];\n");
    out
}

/// One line per run of emoji sharing a subgroup: `/* subgroup */ e(..), e(..),`.
fn subgroup_lines(emoji: &[EmojiRecord]) -> Vec<String> {
    let mut lines: Vec<String> = Vec::new();
    let mut current: Option<&str> = None;
    for record in emoji {
        if current != Some(record.subgroup.as_str()) {
            current = Some(record.subgroup.as_str());
            lines.push(format!("    /* {} */", record.subgroup));
        }
        if let Some(line) = lines.last_mut() {
            line.push(' ');
            line.push_str(&entry(record));
        }
    }
    lines
}

fn entry(record: &EmojiRecord) -> String {
    let group = EmojiGroup::ALL[record.group].variant_name();
    let tones: Vec<String> = record.tones.iter().map(|tone| format!("{tone:?}")).collect();
    let (major, minor) = record.since;
    format!("e({:?}, {:?}, {group}, {major}, {minor}, &[{}]),", record.glyph, record.name, tones.join(", "))
}
